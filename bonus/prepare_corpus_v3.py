import json
import os
from pathlib import Path
import pymupdf

ROOT = Path.cwd()
BONUS = ROOT / "bonus"
OUTPUT = BONUS / "output"
V2 = OUTPUT / "v2/multimodal_corpus.jsonl"
V3 = OUTPUT / "v3/multimodal_corpus.jsonl"

assert V2.exists(), "V2 corpus missing"
assert not V3.exists(), "V3 corpus already exists"

records = [
    json.loads(line)
    for line in V2.read_text(encoding="utf-8").splitlines()
    if line.strip()
]

assert len(records) == 997
existing_ids = {r["id"] for r in records}

new_visuals = [
    {
        "id": "bonus_p63_chart_0",
        "pdf_page": 63,
        "kind": "chart",
        "text": (
            "Figure 1-6 is a vertical bar chart generated by "
            "Python Matplotlib. It shows the distribution of "
            "student letter grades, with letter-grade categories "
            "on the horizontal axis and number of students on "
            "the vertical axis. The bars have different heights."
        )
    },
    {
        "id": "bonus_p180_diagram_0",
        "pdf_page": 180,
        "kind": "diagram",
        "text": (
            "Figure 2-4 is a flowchart of a while statement. "
            "A condition is tested before executing the loop body. "
            "If the condition is true, the suite executes and "
            "control returns to test the condition. If false, "
            "the flow exits the loop."
        )
    }
]

pdf_path = (
    Path(os.environ["DAY6_ROOT"])
    / "starter/data/python_textbook.pdf"
)
assert pdf_path.exists()

image_dir = V3.parent / "visual_pages"
image_dir.mkdir(parents=True, exist_ok=True)

doc = pymupdf.open(pdf_path)

for item in new_visuals:
    assert item["id"] not in existing_ids

    page_no = item["pdf_page"]
    page = doc[page_no - 1]
    filename = f"page_{page_no:03}.png"

    pix = page.get_pixmap(
        matrix=pymupdf.Matrix(1.6, 1.6),
        alpha=False
    )
    pix.save(str(image_dir / filename))

    records.append({
        **item,
        "source_id": "python_wang_2023",
        "bbox": list(page.rect),
        "image_path": f"visual_pages/{filename}",
        "caption_origin": "manually_reviewed_visual"
    })
    print("ADDED:", item["id"])

doc.close()

assert len(records) == 999
assert len({r["id"] for r in records}) == 999

V3.parent.mkdir(parents=True, exist_ok=True)

with V3.open("w", encoding="utf-8") as f:
    for record in records:
        f.write(json.dumps(record, ensure_ascii=False) + "\n")

source_script = BONUS / "hybrid_index_v2.py"
target_script = BONUS / "hybrid_index_v3.py"

assert source_script.exists()
assert not target_script.exists()

script = source_script.read_text(encoding="utf-8-sig")

# Redirect every V2 location to its V3 equivalent.
assert "bonus/output/v2/" in script
assert "bonus_multimodal_v2" in script

script = script.replace(
    "bonus/output/v2/",
    "bonus/output/v3/"
)
script = script.replace(
    "bonus_multimodal_v2",
    "bonus_multimodal_v3"
)

# Update any fixed corpus-size assertions in the index script.
script = script.replace(
    "assert len(records) == 997",
    "assert len(records) == 999"
)

target_script.write_text(script, encoding="utf-8")

print("\n=== BONUS V3 PREPARATION ===")
print("V2 records: 997")
print("Added chart: 1")
print("Added diagram: 1")
print("V3 records:", len(records))
print("V3 corpus:", V3)
print("V3 index script:", target_script)
print("PASS: BONUS V3 CORPUS READY")
